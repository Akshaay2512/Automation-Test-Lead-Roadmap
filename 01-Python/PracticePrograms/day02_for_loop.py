#print 1...10 using for loop

for i in range(10):
    print(i)

# starting and ending range
for j in range(1,11):
    print(j)

#print only even number
for k in range(0,21, 2):
    print(k)

#print only odd number
for k in range(1,21, 2):
    print(k)

#1...10 in descending order
for m in range(10,0,-1):
    print(m)

# increment by 5
for l in range(5,51,5):
    print(l)